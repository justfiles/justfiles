import { createHash } from 'node:crypto'
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import type { Catalog, CatalogApp } from '@justfiles/app/appstore'
import type { Plugin } from 'vite'
import { CATALOG_SCHEMA } from './shared/appstore.ts'

// Dev-only sideload: extra `packages/<dir>` apps to fold into the LOCAL catalog
// so you can launch an in-repo app that isn't a shipped built-in. Driven by the
// `FRIEREN_DEV_APPS` env var (comma-separated dir names) and applied only while
// serving. A production build emits an empty bundled catalog, so a sideloaded app
// cannot ship as a built-in. Build the app first so its `dist/` exists.
//   e.g. FRIEREN_DEV_APPS=app-pixel pnpm dev
const DEV_DIRS = (process.env.FRIEREN_DEV_APPS ?? '')
	.split(',')
	.map((s) => s.trim())
	.filter(Boolean)

// Files we never ship to the store: the generated byte-module + its types.
const SKIP = new Set(['bundle.js', 'bundle.d.ts'])

interface RawManifest {
	id: string
	name: string
	version?: string
	icon?: string
	capabilities?: Record<string, { id: string; scopes: string[] }>
}

function walk(base: string, dir: string, into: Map<string, Uint8Array>): void {
	for (const entry of readdirSync(dir)) {
		const abs = path.join(dir, entry)
		if (statSync(abs).isDirectory()) walk(base, abs, into)
		else {
			const rel = path.relative(base, abs).split(path.sep).join('/')
			if (!SKIP.has(rel)) into.set(rel, readFileSync(abs))
		}
	}
}

// Build (and write) the catalog + per-app files into `<outDir>/appstore`.
// Vite copies `public/` into the client build, so writing there serves the
// assets both in dev (Vite static) and prod (the `ASSETS` binding) — and lets
// `env.ASSETS.fetch('/appstore/...')` work identically on the server.
function emit(root: string, outDir: string, dirs: string[]): void {
	const appstore = path.join(outDir, 'appstore')
	rmSync(appstore, { recursive: true, force: true })
	const apps: CatalogApp[] = []
	for (const dir of dirs) {
		const dist = path.resolve(root, '..', '..', 'packages', dir, 'dist')
		const files = new Map<string, Uint8Array>()
		walk(dist, dist, files)
		const manifestBytes = files.get('manifest.json')
		if (!manifestBytes)
			throw new Error(`appstore: ${dir} has no dist/manifest.json (build it first)`)
		const manifest = JSON.parse(Buffer.from(manifestBytes).toString('utf8')) as RawManifest
		const version = manifest.version ?? '0.0.0'
		const appDir = path.join(appstore, 'apps', manifest.id, version)
		const catalogFiles = [...files]
			.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
			.map(([rel, bytes]) => {
				const dest = path.join(appDir, rel)
				mkdirSync(path.dirname(dest), { recursive: true })
				writeFileSync(dest, bytes)
				return {
					path: rel,
					hash: `sha256-${createHash('sha256').update(bytes).digest('hex')}`,
					size: bytes.byteLength
				}
			})
		apps.push({
			id: manifest.id,
			name: manifest.name,
			version,
			icon: manifest.icon,
			capabilities: manifest.capabilities,
			files: catalogFiles
		})
	}
	const catalog: Catalog = { schema: CATALOG_SCHEMA, apps }
	mkdirSync(appstore, { recursive: true })
	writeFileSync(path.join(appstore, 'catalog.json'), JSON.stringify(catalog, null, '\t'))
}

export function appstore(): Plugin {
	const root = __dirname
	let serving = false
	return {
		name: 'frieren:appstore',
		enforce: 'pre',
		configResolved(config) {
			serving = config.command === 'serve'
		},
		// Runs for both `serve` and `build`. In dev, write into `public/` so Vite's
		// static handler (and the dev `ASSETS` binding) serve fresh bytes on every
		// start; on build, Vite then copies `public/appstore` into `dist/client`.
		// Dev-sideloaded apps (`DEV_DIRS`) are folded in ONLY while serving, so a
		// production build emits an empty bundled catalog.
		buildStart() {
			emit(root, path.resolve(root, 'public'), serving ? DEV_DIRS : [])
		}
	}
}
