import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const read = (path: string) => readFile(new URL(path, root), 'utf8')
const references: Record<string, string> = {}
for (const name of ['ai', 'calendar', 'devkit', 'email', 'image', 'reader', 'volume'])
	references[name] = await read(`capabilities/${name}/contract.ts`)
references.notify = `${await read('capabilities/notify/index.ts')}\n${await read('capabilities/notify/types.ts')}`
const fs = await read('../fs/volume.ts')
references.volume = `${fs.slice(fs.indexOf('export interface Volume {')).split('\n}')[0]}\n}\n${references.volume}`
await writeFile(
	new URL('capabilities/ai/agent/references.ts', root),
	`// biome-ignore-all format: Generated by scripts/build-ai-references.ts from the capability contracts.\nexport const references: Record<string, string> = ${JSON.stringify(references, null, '\t')}\n`
)
