import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import tailwindcss from '@tailwindcss/vite'
import { buildSync } from 'esbuild'
import type { PluginOption } from 'vite'
import type { AppManifest } from './app.ts'
import type { createDevServer, DevServerOptions } from './dev-server.ts'

const DEV_STYLE_URL = '/_kernel-host/dev-style.js'
const DEV_STYLE_ID = '\0kernel-host:dev-style'
const DEV_STYLE_CSS = `/@fs/${new URL('./dev-server.css', import.meta.url).pathname}`

// `kernelHost` is the app package's only build wiring. It has two modes:
//
//   serve  — local dev only. Boots an in-memory kernel that emulates the
//            real host (frieren), via ./dev-server loaded through vite.
//   build  — emits the production artifact: Vite builds the browser
//            `gui.js`; closeBundle emits the headless `app.js`, manifest,
//            and a self-contained `bundle.js` (id, version, manifest, files
//            as Uint8Array). A host (frieren) installs the app by
//            `import paint from '@justfiles/app-paint/bundle'` —
//            no zip step, no copy-to-worker pipeline.
//
// Only bare specifiers + type-only imports here: the config loader
// externalizes this plugin and resolves it with native Node, which can't
// load relative TypeScript siblings (./dev-server goes via ssrLoadModule).
const compile = (entry: string) => {
	const output = buildSync({
		entryPoints: [entry],
		absWorkingDir: dirname(entry),
		bundle: true,
		write: false,
		format: 'esm',
		minify: true
	}).outputFiles[0]
	if (!output) throw new Error(`failed to compile ${entry}`)
	return output.text
}

function readPackageVersion(root: string): string | undefined {
	try {
		const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')) as {
			version?: string
		}
		return pkg.version
	} catch {
		return undefined
	}
}

function walkDist(base: string, dir: string, into: Map<string, Uint8Array>): void {
	for (const entry of readdirSync(dir)) {
		const abs = join(dir, entry)
		if (statSync(abs).isDirectory()) walkDist(base, abs, into)
		else into.set(relative(base, abs).split('\\').join('/'), readFileSync(abs))
	}
}

function emitBuiltinBundle(out: string, manifest: AppManifest): void {
	const files = new Map<string, Uint8Array>()
	walkDist(out, out, files)
	// Skip the generated outputs themselves so a re-run is idempotent.
	files.delete('bundle.js')
	files.delete('bundle.d.ts')
	const entries = [...files]
		.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
		.map(
			([rel, bytes]) =>
				`\t${JSON.stringify(rel)}: b(${JSON.stringify(Buffer.from(bytes).toString('base64'))})`
		)
		.join(',\n')
	const src =
		'// generated by @justfiles/app kernelHost — do not edit\n' +
		'function b(s){const a=atob(s),u=new Uint8Array(a.length);' +
		'for(let i=0;i<a.length;i++)u[i]=a.charCodeAt(i);return u}\n' +
		`const manifest = ${JSON.stringify(manifest)}\n` +
		`const files = {\n${entries}\n}\n` +
		'export default { id: manifest.id, version: manifest.version, manifest, files }\n'
	writeFileSync(resolve(out, 'bundle.js'), src)
	writeFileSync(
		resolve(out, 'bundle.d.ts'),
		"import type { BuiltinBundle } from '@justfiles/app/runtime'\n" +
			'declare const bundle: BuiltinBundle\n' +
			'export default bundle\n'
	)
}

export function kernelHost(opts: DevServerOptions): PluginOption[] {
	const root = process.cwd()
	let emitted = false
	return [
		...tailwindcss(),
		{
			name: 'kernel-host',
			config(_, env) {
				if (env.command === 'serve') return { appType: 'custom' }
				return {
					base: './',
					build: {
						outDir: 'dist',
						emptyOutDir: true,
						// Library mode: preserve the entry's `export { gui }` (an app
						// build tree-shakes it away — the sdk is sideEffects:false).
						lib: {
							entry: resolve(root, opts.gui),
							formats: ['es'],
							fileName: () => 'gui.js'
						},
						rollupOptions: {
							// The host serves a single shared React via /vendor/*.js
							// (see apps/frieren importmap). Apps emit bare specifiers
							// and the browser resolves them through the importmap —
							// one URL, one React instance across host and every app.
							external: [
								'react',
								'react-dom',
								'react-dom/client',
								'react/jsx-runtime',
								'react/jsx-dev-runtime'
							]
						}
					}
				}
			},
			resolveId(id) {
				if (id === DEV_STYLE_URL) return DEV_STYLE_ID
				return null
			},
			load(id) {
				if (id === DEV_STYLE_ID) return `import ${JSON.stringify(DEV_STYLE_CSS)}`
				return null
			},
			configureServer(server) {
				return async () => {
					const mod = (await server.ssrLoadModule('@justfiles/app/dev-server')) as {
						createDevServer: typeof createDevServer
					}
					server.middlewares.use(await mod.createDevServer(server.config.root, opts))
				}
			},
			closeBundle() {
				if (emitted) return
				emitted = true
				const out = resolve(root, 'dist')
				mkdirSync(out, { recursive: true })
				writeFileSync(resolve(out, 'app.js'), compile(resolve(root, opts.app)))
				const manifest: AppManifest = {
					id: opts.id,
					name: opts.name,
					description: opts.description,
					// Fall back to package.json#version so apps don't have to thread it
					// through the kernelHost() call by hand. Explicit opts.version wins.
					version: opts.version ?? readPackageVersion(root),
					icon: opts.icon,
					app: 'app.js',
					gui: 'gui.js'
				}
				writeFileSync(resolve(out, 'manifest.json'), JSON.stringify(manifest, null, '\t'))
				emitBuiltinBundle(out, manifest)
			}
		}
	]
}
